//! Verified `ac_fun`, as in `verus/src/ac_fun.rs`: a user supplies `f` with proofs that it is
//! commutative and associative, and Prusti derives the CRDT law `commutative` for `ac_fun f`, whose
//! effect `e` on the state `s` is `f e s`.
//!
//! Unlike Verus, Prusti needs no separate `spec_f`: a `#[pure]` function is ordinary Rust that
//! Prusti checks to be deterministic and side-effect free, and it can then appear in specs.
//!
//! The element type is fixed per trait (`AcFunI64`, `AcFunPair`) rather than a parameter of one
//! `AcFun` trait: with the Prusti release this was checked with (v-2026-10-27-1410), the body of a
//! `#[pure]` method in an `impl` is not used when the trait's signature mentions a type parameter
//! or an associated type, so no law about it can be proved. Specs generated by `macro_rules!` were
//! not reliable either, hence the traits are written out.

use prusti_contracts::*;

/// The argument of `ac_fun` on `i64`: a pure `f` and the two laws, stated as lemmas. A lemma is a
/// function with no effect whose postcondition is the law; calling it brings the law into scope.
/// An `impl` inherits the postconditions, and Prusti checks its (usually empty) body against them.
pub trait AcFunI64 {
    #[pure]
    fn f(a: i64, b: i64) -> i64;

    #[ensures(Self::f(a, b) === Self::f(b, a))]
    fn comm(a: i64, b: i64);

    #[ensures(Self::f(Self::f(a, b), c) === Self::f(a, Self::f(b, c)))]
    fn assoc(a: i64, b: i64, c: i64);
}

/// `commutative` of `ac_fun f`: `f e₂ (f e₁ s) = f (f e₂ e₁) s = f (f e₁ e₂) s = f e₁ (f e₂ s)`.
#[ensures(F::f(e2, F::f(e1, s)) === F::f(e1, F::f(e2, s)))]
pub fn commutative_i64<F: AcFunI64>(e1: i64, e2: i64, s: i64) {
    F::assoc(e2, e1, s);
    F::comm(e2, e1);
    F::assoc(e1, e2, s);
}

/// A pair of `u64`s, e.g. `(timestamp, value)`.
pub type Pair = (u64, u64);

/// `AcFunI64` on `Pair`.
pub trait AcFunPair {
    #[pure]
    fn f(a: Pair, b: Pair) -> Pair;

    #[ensures(Self::f(a, b) === Self::f(b, a))]
    fn comm(a: Pair, b: Pair);

    #[ensures(Self::f(Self::f(a, b), c) === Self::f(a, Self::f(b, c)))]
    fn assoc(a: Pair, b: Pair, c: Pair);
}

/// `commutative_i64` on `Pair`.
#[ensures(F::f(e2, F::f(e1, s)) === F::f(e1, F::f(e2, s)))]
pub fn commutative_pair<F: AcFunPair>(e1: Pair, e2: Pair, s: Pair) {
    F::assoc(e2, e1, s);
    F::comm(e2, e1);
    F::assoc(e1, e2, s);
}

/// `max_int`: `join` on `i64`.
pub struct MaxInt;

#[refine_trait_spec]
impl AcFunI64 for MaxInt {
    #[pure]
    fn f(a: i64, b: i64) -> i64 {
        if a >= b {
            a
        } else {
            b
        }
    }

    fn comm(a: i64, b: i64) {}

    fn assoc(a: i64, b: i64, c: i64) {}
}

/// `max_int` as a CRDT: its effects commute.
#[ensures(MaxInt::f(e2, MaxInt::f(e1, s)) === MaxInt::f(e1, MaxInt::f(e2, s)))]
pub fn max_int_commutes(e1: i64, e2: i64, s: i64) {
    commutative_i64::<MaxInt>(e1, e2, s);
}
